const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const MANIFEST_PATH = path.join(ROOT, 'src', 'runtime-manifest.json');

function readRuntimeManifest(root = ROOT) {
  const manifestPath = path.join(root, 'src', 'runtime-manifest.json');
  return JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
}

function runtimeSourceFilesForManifest(manifest) {
  return [...new Set([
    manifest.loader,
    manifest.authorityModule,
    ...(Array.isArray(manifest.modules) ? manifest.modules : []),
    ...(Array.isArray(manifest.scripts) ? manifest.scripts : []),
  ].filter(file => typeof file === 'string' && file.trim()))];
}

function runtimeSourceDigestForManifest(root = ROOT, manifest = readRuntimeManifest(root)) {
  if (!manifest.bundle || !Array.isArray(manifest.scripts) || !manifest.scripts.length) {
    throw new Error('runtime manifest bundle/scripts 계약이 올바르지 않습니다.');
  }
  const sources = runtimeSourceFilesForManifest(manifest).map(file => ({
    file,
    content: fs.readFileSync(path.join(root, file), 'utf8').replace(/\s+$/, ''),
  }));
  return crypto.createHash('sha256')
    .update(sources.map(item => item.file + '\0' + item.content).join('\0'))
    .digest('hex');
}

function readExistingRuntimeBundleMetadata(bundlePath) {
  if (!fs.existsSync(bundlePath)) return null;
  try {
    const content = fs.readFileSync(bundlePath, 'utf8');
    const marker = 'window.__KUASANGSE_BUNDLE_METADATA__ = ';
    const start = content.indexOf(marker);
    const end = start < 0 ? -1 : content.indexOf(';\n', start);
    return start >= 0 && end >= 0
      ? JSON.parse(content.slice(start + marker.length, end))
      : null;
  } catch (_) {
    return null;
  }
}

function nextRuntimeBuildId(buildId = '') {
  const current = String(buildId || '').trim() || 'runtime';
  const marker = current.lastIndexOf('v');
  const version = Number(current.slice(marker + 1));
  if (marker >= 0 && Number.isInteger(version) && version >= 0) {
    return current.slice(0, marker + 1) + String(version + 1);
  }
  return current + '-v2';
}

function syncRuntimeManifestBuildId(root = ROOT, manifest = readRuntimeManifest(root)) {
  const bundlePath = path.join(root, manifest.bundle || '');
  const existingMetadata = readExistingRuntimeBundleMetadata(bundlePath);
  const sourceDigest = runtimeSourceDigestForManifest(root, manifest);
  const digestUnchanged = existingMetadata?.sourceDigest === sourceDigest;
  const manifestAlreadyStamped = String(manifest.sourceDigest || '') === sourceDigest;
  if (!existingMetadata?.sourceDigest || (digestUnchanged && manifestAlreadyStamped)) {
    return manifest;
  }
  // 예전에는 dist 와 매니페스트의 buildId 가 어긋나면 번호를 그대로 뒀다.
  // 그런데 git restore 직후가 정확히 그 상태(dist=v1258, manifest=v1255)라,
  // 내용이 바뀌었는데도 번호가 유지돼 '같은 번호 다른 내용' 이 만들어졌다.
  // 그러면 브라우저 가드는 영원히 침묵한다. 내용이 바뀌었으면 번호를 올린다.
  const nextManifest = {
    ...manifest,
    ...(digestUnchanged ? {} : { buildId: nextRuntimeBuildId(manifest.buildId) }),
    // 번호는 되감길 수 있어도 내용 지문은 내용에서 나온다.
    // 가드가 이 값을 함께 봐서 번호 재사용을 잡아낸다.
    sourceDigest,
  };
  fs.writeFileSync(
    path.join(root, 'src', 'runtime-manifest.json'),
    JSON.stringify(nextManifest, null, 2) + '\n',
    'utf8',
  );
  return nextManifest;
}

function runtimeBundleContent(root = ROOT, manifest = readRuntimeManifest(root)) {
  if (!manifest.bundle || !Array.isArray(manifest.scripts) || !manifest.scripts.length) {
    throw new Error('runtime manifest bundle/scripts 계약이 올바르지 않습니다.');
  }
  const sources = manifest.scripts.map(file => ({
    file,
    content: fs.readFileSync(path.join(root, file), 'utf8').replace(/\s+$/, ''),
  }));
  const sourceDigest = runtimeSourceDigestForManifest(root, manifest);
  const metadata = {
    schema: 'kuasangse.runtime.bundle.v1',
    buildId: manifest.buildId,
    sourceDigest,
    sources: sources.map(item => item.file),
  };
  const header = [
    '/* This file is generated by tools/build_runtime_bundle.cjs. Do not edit directly. */',
    `window.__KUASANGSE_BUNDLE_METADATA__ = ${JSON.stringify(metadata)};`,
  ].join('\n');
  const body = sources.map(item => `\n\n/* ===== ${item.file} ===== */\n${item.content}`).join('');
  return `${header}${body}\n//# sourceURL=kuasangse-runtime.bundle.js\n`;
}

function verifyRuntimeBundle(root = ROOT) {
  const manifest = readRuntimeManifest(root);
  const bundlePath = path.join(root, manifest.bundle || '');
  if (!manifest.bundle || !fs.existsSync(bundlePath)) return false;
  return fs.readFileSync(bundlePath, 'utf8') === runtimeBundleContent(root, manifest);
}

function writeRuntimeBundle(root = ROOT) {
  const manifest = syncRuntimeManifestBuildId(root);
  const bundlePath = path.join(root, manifest.bundle);
  fs.mkdirSync(path.dirname(bundlePath), { recursive: true });
  fs.writeFileSync(bundlePath, runtimeBundleContent(root, manifest), 'utf8');
  return bundlePath;
}

if (require.main === module) {
  if (process.argv.includes('--check')) {
    if (!verifyRuntimeBundle()) {
      console.error('runtime bundle이 현재 manifest/source와 다릅니다. node tools/build_runtime_bundle.cjs를 실행하세요.');
      process.exitCode = 1;
    } else {
      console.log('runtime bundle verified');
    }
  } else {
    console.log(writeRuntimeBundle());
  }
}

module.exports = {
  readRuntimeManifest,
  runtimeBundleContent,
  verifyRuntimeBundle,
  writeRuntimeBundle,
  nextRuntimeBuildId,
  syncRuntimeManifestBuildId,
};
